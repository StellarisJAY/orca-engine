#include "skybox_cube.h"

void SkyboxCube::create_geometry(std::vector<Vector3> &r_vertices, std::vector<uint32_t> &r_indices)
{
    // 8 个角。只有位置参与天空盒采样，因此相邻面共享顶点即可，
    // 不需要为了法线/UV 拆分成 24 个顶点。
    r_vertices = {
        {-1, -1, -1}, // 0
        {1, -1, -1},  // 1
        {1, 1, -1},   // 2
        {-1, 1, -1},  // 3
        {-1, -1, 1},  // 4
        {1, -1, 1},   // 5
        {1, 1, 1},    // 6
        {-1, 1, 1},   // 7
    };

    // 每个面两个三角形，逆时针环绕，法线朝外。
    // 天空盒关闭背面剔除时环绕方向不影响结果，但保持与普通立方体一致便于复用。
    r_indices = {
        0, 3, 2, 0, 2, 1, // -Z
        4, 5, 6, 4, 6, 7, // +Z
        0, 4, 7, 0, 7, 3, // -X
        1, 2, 6, 1, 6, 5, // +X
        0, 1, 5, 0, 5, 4, // -Y
        3, 7, 6, 3, 6, 2, // +Y
    };
}
